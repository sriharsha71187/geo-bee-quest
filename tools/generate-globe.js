/* Generates js/globe-data.js (and copies the small map libraries into
 * js/vendor/) for the Learn globe, from public-domain Natural Earth data
 * (world-atlas npm package). Run with:
 *   npm install world-atlas@2.0.2 topojson-client@3.1.0 d3-geo@3.1.1 d3-array@3.2.4
 *   NODE_PATH=./node_modules node tools/generate-globe.js
 * Output: window.GEO_GLOBE = {
 *   topo:  Natural Earth 110m countries as TopoJSON, names matching data.js
 *          (the same set and names as the flat world map, so progress ids
 *          "wm:<name>" line up),
 *   dots:  {name: [lon, lat]} for countries too small to be in the 110m set
 *          (from the 50m set), drawn as tappable dots,
 *   small: names in the 110m set too small to tap as a shape (also get a dot)
 * }
 */
const fs = require("fs");
const path = require("path");
const topojson = require("topojson-client");
const d3 = require("d3-geo");

// Natural Earth name → our data.js name (kept in step with generate-maps.js)
const ALIASES = {
  "United States of America": "United States",
  "Dem. Rep. Congo": "Democratic Republic of the Congo",
  "Côte d'Ivoire": "Ivory Coast",
  "Bahamas": "The Bahamas",
  "Dominican Rep.": "Dominican Republic",
  "Czech Republic": "Czechia",
  "Czechia": "Czechia",
  "Türkiye": "Turkey",
  "Bosnia and Herz.": "Bosnia and Herzegovina",
  "S. Sudan": "South Sudan",
  "Central African Rep.": "Central African Republic",
  "Congo": "Republic of the Congo",
  "Eq. Guinea": "Equatorial Guinea",
  "eSwatini": "Eswatini",
  "Solomon Is.": "Solomon Islands",
  "Macedonia": "North Macedonia",
  "St. Kitts and Nevis": "Saint Kitts and Nevis",
  "St. Vin. and Gren.": "Saint Vincent and the Grenadines",
  "Saint Lucia": "Saint Lucia",
  "Antigua and Barb.": "Antigua and Barbuda",
  "São Tomé and Principe": "Sao Tome and Principe",
  "Marshall Is.": "Marshall Islands",
  "Micronesia": "Micronesia",
  "Vatican": "Vatican City",
};
const nameOf = (f) => ALIASES[f.properties.name] || f.properties.name;

const atlas = (f) => JSON.parse(fs.readFileSync(require.resolve("world-atlas/" + f), "utf8"));
const topo = atlas("countries-110m.json");
for (const g of topo.objects.countries.geometries) {
  g.properties = { name: ALIASES[g.properties.name] || g.properties.name };
  delete g.id;
}
const have = new Set(topo.objects.countries.geometries.map((g) => g.properties.name));
const r2 = (x) => Math.round(x * 100) / 100;

// shapes too small to tap on a whole-Earth globe (steradians)
const SMALL = 0.0004;
const small = topojson.feature(topo, topo.objects.countries).features
  .filter((f) => d3.geoArea(f) < SMALL).map((f) => f.properties.name);

const t50 = atlas("countries-50m.json");
const dots = {};
for (const f of topojson.feature(t50, t50.objects.countries).features) {
  const n = nameOf(f);
  if (have.has(n)) continue;
  const c = d3.geoCentroid(f);
  if (isFinite(c[0])) dots[n] = [r2(c[0]), r2(c[1])];
}

// in data.js but in neither Natural Earth set
if (!dots.Tuvalu) dots.Tuvalu = [179.2, -8.52];

const out = `/* Generated by tools/generate-globe.js from world-atlas (Natural Earth,
 * public domain). Do not edit by hand. */
window.GEO_GLOBE = ${JSON.stringify({ topo, dots, small })};
`;
const OUT = path.join(__dirname, "..", "js", "globe-data.js");
fs.writeFileSync(OUT, out);

// the three small libraries the globe draws with (ISC licensed; their
// copyright headers stay in the files)
const VEND = path.join(__dirname, "..", "js", "vendor");
fs.mkdirSync(VEND, { recursive: true });
for (const [pkg, file] of [["d3-array", "d3-array.min.js"], ["d3-geo", "d3-geo.min.js"], ["topojson-client", "topojson-client.min.js"]]) {
  const dir = require.resolve.paths(pkg).map((d) => path.join(d, pkg, "dist", file)).find((f) => fs.existsSync(f));
  fs.copyFileSync(dir, path.join(VEND, file));
}
console.error(`wrote ${OUT}: ${have.size} shapes, ${Object.keys(dots).length} dots, ${small.length} small, ${(out.length / 1024).toFixed(0)} KB`);
